"""构建 corpus3 = 现有 corpus2 + 新下载的 pypi 源码。

## 为什么不用 `codemind prepare`

`prepare` 会**重新训练分词器**（`--vocab` / `--tokenizer-chars` 都是 BPE 训练参数）。
那会**让现有检查点全部作废** —— 词表一变，权重就对不上了。

所以本脚本**复用 `data/corpus2/tokenizer.json`**，只做编码与拼接。

## 为什么交错而不是首尾拼接

如果 corpus2 全放前面、pypi 全放后面，训练时**后半段只见 pypi**。
两种来源的代码风格不同，会让 loss 出现人为的台阶，且后半段分布单一。
**按块交错**能让每个训练窗口里两种来源都在场。

用法::

    python tools/build_corpus3.py --out data/corpus3 --block 2000000
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, r"E:\AI")
from codemind.tokenizer import BPETokenizer  # noqa: E402

ROOT = Path(r"E:\AI")
EOT = 256
KEEP_EXT = {".py", ".c", ".h", ".cpp", ".hpp", ".pyx", ".pyi"}
BAD_PATH = re.compile(
    r"(^|/)(vendor|_vendor|vendored|third_party|node_modules|bower_components|"
    r"testdata|snapshots|__snapshots__|fixtures|docs?/build|"
    r"\.git|\.tox|\.eggs|build|dist|\.mypy_cache)(/|$)", re.I)
BAD_NAME = re.compile(
    r"(_pb2\.py$|_pb2_grpc\.py$|\.tab\.c$|\.tab\.h$|lex\.yy\.c$|"
    r"parser\.out\.|\.min\.(js|css)$|_generated\.|\.generated\.)", re.I)
BAD_TEXT = re.compile(
    r"(Code generated by|DO NOT EDIT|autogenerated|Automatically generated|"
    r"Generated by Cython|@generated)", re.I)
MAX_BYTES = 1_000_000


def load_corpus(d: Path) -> np.ndarray:
    m = json.loads(sorted(d.glob("*.meta.json"))[0].read_text(encoding="utf-8"))
    arrs = [np.fromfile(d / f, dtype=np.uint16)
            for f in list(m["train_files"]) + list(m["val_files"])]
    return np.concatenate(arrs)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", default="data/corpus2")
    ap.add_argument("--new-src", default="corpora/pypi_src")
    ap.add_argument("--out", default="data/corpus3")
    ap.add_argument("--name", default="corpus3")
    ap.add_argument("--block", type=int, default=2_000_000)
    ap.add_argument("--shard-tokens", type=int, default=8_000_000)
    ap.add_argument("--val-ratio", type=float, default=0.01)
    args = ap.parse_args()

    tok = BPETokenizer.load(ROOT / args.old / "tokenizer.json")
    print(f"[c3] 复用分词器 vocab={tok.vocab_size}（不重新训练，保证检查点兼容）")

    old = load_corpus(ROOT / args.old)
    print(f"[c3] 旧语料 {args.old}: {len(old):,} token")

    src = ROOT / args.new_src
    t0 = time.time()
    parts: list[np.ndarray] = []
    n_files = n_tok = 0
    skipped = 0
    for f in src.rglob("*"):
        if not f.is_file() or f.suffix not in KEEP_EXT:
            continue
        if BAD_PATH.search(f.as_posix()) or BAD_NAME.search(f.name):
            skipped += 1
            continue
        try:
            if f.stat().st_size > MAX_BYTES:
                skipped += 1
                continue
            text = f.read_text(encoding="utf-8", errors="strict")
        except (OSError, UnicodeDecodeError):
            skipped += 1
            continue
        if len(text.strip()) < 50 or BAD_TEXT.search(text[:2000]):
            skipped += 1
            continue
        ids = tok.encode(text, allow_special=False)
        if len(ids) < 10:
            skipped += 1
            continue
        parts.append(np.asarray(ids + [EOT], dtype=np.uint16))
        n_files += 1
        n_tok += len(ids) + 1
        if n_files % 5000 == 0:
            print(f"    编码 {n_files:,} 个文件 / {n_tok/1e6:.1f}M token "
                  f"/ {(time.time()-t0)/60:.1f} 分钟", flush=True)

    new = np.concatenate(parts) if parts else np.zeros(0, dtype=np.uint16)
    print(f"[c3] 新语料 {n_files:,} 个文件 / {len(new):,} token "
          f"（跳过 {skipped:,}）/ {(time.time()-t0)/60:.1f} 分钟")

    # 按块交错，避免"后半段只见一种来源"
    b = args.block
    mixed = []
    i = j = 0
    while i < len(old) or j < len(new):
        if i < len(old):
            mixed.append(old[i:i + b]); i += b
        if j < len(new):
            mixed.append(new[j:j + b]); j += b
    mixed_arr = np.concatenate(mixed)
    print(f"[c3] 交错后 {len(mixed_arr):,} token（块 {b:,}）")

    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob("*.bin"):
        f.unlink()

    n_val = int(len(mixed_arr) * args.val_ratio)
    train, val = mixed_arr[:len(mixed_arr) - n_val], mixed_arr[len(mixed_arr) - n_val:]

    def write(arr: np.ndarray, split: str) -> list[str]:
        names = []
        n_sh = max(1, (len(arr) + args.shard_tokens - 1) // args.shard_tokens)
        for k in range(n_sh):
            name = f"{args.name}.{split}{k:05d}.bin"
            arr[k * args.shard_tokens:(k + 1) * args.shard_tokens].tofile(out / name)
            names.append(name)
        return names

    tr, va = write(train, "train"), write(val, "val")
    (out / f"{args.name}.meta.json").write_text(json.dumps({
        "name": args.name, "dtype": "uint16",
        "train_files": tr, "val_files": va,
        "total_tokens": int(len(mixed_arr)), "vocab_size": tok.vocab_size,
        "n_docs": n_files, "created_at": time.time(),
        "sources": [str(ROOT / args.old), str(ROOT / args.new_src)],
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    import shutil
    shutil.copy2(ROOT / args.old / "tokenizer.json", out / "tokenizer.json")

    print(f"\n[c3] ✓ {out}")
    print(f"      训练 {len(train):,} / 验证 {len(val):,} token")
    print(f"      分片 {len(tr)} 训练 + {len(va)} 验证")
    n = 20.46e6
    print(f"\n  20.46M 模型 Chinchilla = {n*20/1e6:,.0f}M token"
          f" = {n*20/len(train):.1f} epoch")
    print(f"  预测时长 @ 953 tok/s = {n*20/953/86400:.1f} 天")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
