"""多进程编码 pypi 源码 → token 分片。

## 为什么用多进程而不是多线程

BPE 分词是**纯 Python CPU 密集**任务，**GIL 会让多线程完全无效**。
多进程每个 worker 有独立解释器，能真正并行。

## 与 `filter_pypi.py` 的关系

那个是**单进程 + 只统计**。这个是多进程 + 产出分片。
过滤规则**逐条保持一致**（用同一份正则），否则两边的数字对不上。

## 为什么 worker 各写各的临时文件

如果把 token 数组通过 `Pool` 返回值传回主进程，会经过 pickle 序列化 ——
几 GB 的数据来回拷会**吃掉全部收益**。让 worker 直接写 `.npy`，主进程只读元信息。

用法::

    python tools/encode_pypi_mp.py --src corpora/pypi_src --out data/pypi_tok \\
        --procs 8 --tokenizer data/corpus3/tokenizer.json
"""
from __future__ import annotations

import argparse
import hashlib
import multiprocessing as mp
import os
import re
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(r"E:\AI")
EOT = 256
KEEP_EXT = {".py", ".c", ".h", ".cpp", ".hpp", ".pyx", ".pyi"}
BAD_PATH = re.compile(
    r"(^|/)(vendor|_vendor|vendored|third_party|node_modules|bower_components|"
    r"testdata|snapshots|__snapshots__|fixtures|docs?/build|"
    r"\.git|\.tox|\.eggs|build|dist|\.mypy_cache)(/|$)", re.I)
BAD_NAME = re.compile(
    r"(_pb2\.py$|_pb2_grpc\.py$|\.tab\.c$|\.tab\.h$|lex\.yy\.c$|"
    r"parser\.out\.|\.min\.(js|css)$|_generated\.|\.generated\.)", re.I)
BAD_TEXT = re.compile(
    r"(Code generated by|DO NOT EDIT|autogenerated|Automatically generated|"
    r"Generated by Cython|@generated)", re.I)
MAX_BYTES = 1_000_000

_TOK = None
_TMPDIR: Path | None = None


def _init(tok_path: str, tmpdir: str) -> None:
    """每个 worker 加载自己的分词器（不能跨进程共享）。"""
    global _TOK, _TMPDIR
    sys.path.insert(0, str(ROOT))
    from codemind.tokenizer import BPETokenizer
    _TOK = BPETokenizer.load(Path(tok_path))
    _TMPDIR = Path(tmpdir)
    _TMPDIR.mkdir(parents=True, exist_ok=True)


def _one(f: str) -> tuple[str, int, int] | None:
    """过滤 + 编码单个文件，返回 (临时文件名, token 数, 字节数)。

    ## ⚠️ 两个必须的防护（都被实测打出来过）

    **① 临时文件写在扁平目录，不写在源文件旁边。**
    Windows 默认有 **260 字符路径上限**。有的包目录嵌套极深，例如
    `pi_flash_attn-2.8.2/csrc/composable_kernel/.../device_..._instance.cpp`
    —— 在它旁边加 `.npy` 直接超限，`np.save` 抛 `FileNotFoundError`。

    **② 整个函数包在 try 里。**
    第一次跑到 800,000/1,125,091 时，就是**一个**超长路径的文件抛异常，
    异常往上穿过 `pool.imap_unordered`，**把整个 20 分钟的编码任务打死了**。
    单个文件的问题不该拖垮全局。
    """
    try:
        p = Path(f)
        if p.suffix not in KEEP_EXT:
            return None
        # **只看相对路径**，避免绝对路径本身就超长导致正则/判断行为异常
        rel = p.as_posix()
        if BAD_PATH.search(rel) or BAD_NAME.search(p.name):
            return None
        if p.stat().st_size > MAX_BYTES:
            return None
        text = p.read_text(encoding="utf-8", errors="strict")
        if len(text.strip()) < 50 or BAD_TEXT.search(text[:2000]):
            return None
        ids = _TOK.encode(text, allow_special=False)
        if len(ids) < 10:
            return None
        arr = np.asarray(ids + [EOT], dtype=np.uint16)
        # ⚠️ 扁平 + 哈希命名：路径长度恒定，不受源目录深度影响
        tmp = str(_TMPDIR / (hashlib.md5(f.encode("utf-8")).hexdigest() + ".npy"))
        np.save(tmp, arr)
        return (tmp, len(arr), arr.nbytes)
    except Exception:
        return None


def chunks(lst: list, n: int):
    k = max(1, (len(lst) + n - 1) // n)
    for i in range(0, len(lst), k):
        yield lst[i:i + k]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="corpora/pypi_src")
    ap.add_argument("--out", default="data/pypi_tok")
    ap.add_argument("--tokenizer", default="data/corpus3/tokenizer.json")
    ap.add_argument("--procs", type=int, default=8)
    ap.add_argument("--name", default="pypi")
    ap.add_argument("--shard-tokens", type=int, default=8_000_000)
    args = ap.parse_args()

    tok_path = str(ROOT / args.tokenizer)
    src = ROOT / args.src
    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)

    files = [str(f) for f in src.rglob("*") if f.is_file()]
    print(f"[mp] 候选 {len(files):,} 个文件  worker {args.procs}")
    t0 = time.time()

    groups = list(chunks(files, args.procs))
    done = kept = toks = 0
    parts: list[str] = []
    tmpdir = str(ROOT / "runs/_verify/_npy")
    with mp.Pool(args.procs, initializer=_init, initargs=(tok_path, tmpdir)) as pool:
        for gi, res in enumerate(pool.imap_unordered(_one, files, chunksize=64)):
            done += 1
            if res:
                kept += 1
                toks += res[1]
                parts.append(res[0])
            if done % 20000 == 0:
                el = time.time() - t0
                print(f"  {done:,}/{len(files):,}  保留 {kept:,}  "
                      f"{toks/1e6:.1f}M token  {el/60:.1f} 分钟  "
                      f"({done/el:.0f} 文件/秒)", flush=True)

    el = time.time() - t0
    print(f"[mp] 编码完成 {kept:,} 个文件 / {toks:,} token / {el/60:.1f} 分钟")
    if not parts:
        print("[mp] ✗ 没有可编码的文件")
        return 1

    print(f"[mp] 合并 {len(parts):,} 个临时文件…")
    arrs = [np.load(p) for p in parts]
    arr = np.concatenate(arrs)
    print(f"[mp] 合计 {len(arr):,} token")

    n_sh = max(1, (len(arr) + args.shard_tokens - 1) // args.shard_tokens)
    names = []
    for i in range(n_sh):
        nm = f"{args.name}.train{i:05d}.bin"
        arr[i * args.shard_tokens:(i + 1) * args.shard_tokens].tofile(out / nm)
        names.append(nm)
    (out / f"{args.name}.meta.json").write_text(
        __import__("json").dumps(
            {"name": args.name, "dtype": "uint16", "train_files": names,
             "val_files": [], "total_tokens": int(len(arr)),
             "n_docs": kept, "created_at": time.time(),
             "sources": [str(src)]}, ensure_ascii=False, indent=1),
        encoding="utf-8")
    print(f"[mp] ✓ {out}  {n_sh} 个分片")

    for p in parts:
        try:
            os.remove(p)
        except OSError:
            pass
    return 0


if __name__ == "__main__":
    mp.freeze_support()
    raise SystemExit(main())
