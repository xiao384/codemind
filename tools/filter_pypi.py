"""过滤 pypi 源码 + 用**项目分词器**精确计数。

## 为什么必须过滤

本项目已有三次"文件很大、可用量塌到几乎为零"的记录：

| 案例 | 表面 | 实际可用 |
|---|---|---|
| JS/TS | 112.6 MB / 5,608 文件 | **3.3 MB / 185 文件（2.9%）** |
| 图片 | 3,310 个 / 126 MB | **156 个而且没有配文** |
| firefly | 1.17 GB | 中位答案 44 字符（大量是分类任务） |

**而 pypi sdist 里塞了大量非"人写代码"的东西**：
打包好的 JS/CSS、vendored 依赖、生成代码、测试快照。

## 为什么不用"2.4 字符/token"估算

那是**代码语料的平均值**。不同包差异很大（有的全是长标识符，有的全是短行）。
**只有项目自己的 4096 分词器编码出来的数才对得上 Chinchilla。**
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, r"E:\AI")
from codemind.tokenizer import BPETokenizer  # noqa: E402

SRC = Path(r"E:\AI\corpora\pypi_src")
KEEP_EXT = {".py", ".c", ".h", ".cpp", ".hpp", ".pyx", ".pyi"}

#: 路径里出现这些片段就排除
BAD_PATH = re.compile(
    r"(^|/)(vendor|_vendor|vendored|third_party|node_modules|bower_components|"
    r"testdata|snapshots|__snapshots__|fixtures|docs?/build|"
    r"\.git|\.tox|\.eggs|build|dist|\.mypy_cache)(/|$)",
    re.I,
)

#: 文件名匹配就排除
BAD_NAME = re.compile(
    r"(_pb2\.py$|_pb2_grpc\.py$|\.tab\.c$|\.tab\.h$|lex\.yy\.c$|"
    r"parser\.out\.|\.min\.(js|css)$|_generated\.|\.generated\.)",
    re.I,
)

#: 内容里出现就排除（生成代码的标记）
BAD_TEXT = re.compile(
    r"(Code generated by|DO NOT EDIT|autogenerated|Automatically generated|"
    r"Generated by Cython|@generated)",
    re.I,
)

MAX_BYTES = 1_000_000        # 单文件上限（超长文件通常是数据不是逻辑）


def main() -> int:
    tok = BPETokenizer.load(Path(r"E:\AI\data\corpus2\tokenizer.json"))
    print(f"分词器 vocab={tok.vocab_size}")

    stats = {"扫描": 0, "扩展名不符": 0, "路径排除": 0, "文件名排除": 0,
             "内容排除": 0, "过大": 0, "空": 0, "读取失败": 0, "保留": 0}
    kept_bytes = 0
    kept = 0
    tokens = 0
    per_ext: dict[str, int] = {}

    for f in SRC.rglob("*"):
        if not f.is_file():
            continue
        stats["扫描"] += 1
        if f.suffix not in KEEP_EXT:
            stats["扩展名不符"] += 1
            continue
        rel = f.as_posix()
        if BAD_PATH.search(rel):
            stats["路径排除"] += 1
            continue
        if BAD_NAME.search(f.name):
            stats["文件名排除"] += 1
            continue
        try:
            if f.stat().st_size > MAX_BYTES:
                stats["过大"] += 1
                continue
            text = f.read_text(encoding="utf-8", errors="strict")
        except (OSError, UnicodeDecodeError):
            stats["读取失败"] += 1
            continue
        if len(text.strip()) < 50:
            stats["空"] += 1
            continue
        if BAD_TEXT.search(text[:2000]):
            stats["内容排除"] += 1
            continue

        kept += 1
        kept_bytes += len(text.encode("utf-8"))
        ids = tok.encode(text, allow_special=False)
        tokens += len(ids) + 1          # +1 = 文档间的 EOT
        per_ext[f.suffix] = per_ext.get(f.suffix, 0) + 1

    print()
    print("  ---- 过滤明细 ----")
    for k, v in stats.items():
        if v:
            print(f"    {k:12}{v:>9,}")
    print()
    print(f"  **保留 {kept:,} 个文件 / {kept_bytes/1e6:.1f} MB**")
    print(f"  **实测 token: {tokens:,} = {tokens/1e6:.1f}M**")
    print()
    print("  按扩展名：")
    for e, c in sorted(per_ext.items(), key=lambda x: -x[1]):
        print(f"    {e:8}{c:>9,}")
    print()
    if stats["扫描"]:
        print(f"  可用率（按文件数）: {kept/stats['扫描']*100:.1f}%")
    print(f"  字符/token 实测: {kept_bytes/max(1,tokens):.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
